/********** Queue
 * Add only from back; out only from first ; FIFO
 * Enqueue - adding element inside queue
 * Dequeue - removing element
 * Peek/Front - return first element of queue
 * ex: ticket counter, OS task scheduling, printer
 */

/********* Stack
 * Add element only from top; out also from top; LIFO
 * Push - add element
 * Pop - remove element
 * Peek/Top - find out the topmost element of stack
 * ex: stack of books, Undo feature, browsing feature, recursion
 * All the arrays in js is already stack
 */

/******* Why do we need them?
 * Organise data logically
 * Order of operation matters
 * Optimise time/space complexity
 * Recursion, level order traversal, breadth first search, depth first search
 */

/******* When we already have arrays why do we need stack/queue
 * For restricted access (top only); Stack === array (with restricted access)
 * Don't do random access of data inside stack; don't modify data at any index directly
 * They follow discipline unlike array
 */
